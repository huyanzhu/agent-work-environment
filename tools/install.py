#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""AI-OS 接入器 —— 把本仓库接入 DSH（DeepSeek Harness）。

（自 `另一仓库` 移植进 AI-OS 本体；差异见文末「移植说明」。）

用法（Windows / macOS / Linux 通用）：

    python tools/install.py                 # 预演：只检查 + 显示将要写入的内容（默认，不改任何文件）
    python tools/install.py --apply         # 写入（会先备份 cordis.patch.yml）
    python tools/install.py --profile web   # 指定 profile（默认自动选择/询问）
    python tools/install.py --list          # 只看环境与 profile，不做任何改动
    python tools/install.py --repo <路径>   # 接入**另一个仓库**（默认 = 本脚本所在仓库）

它做什么
    1. 环境检查：DSH(~/.dsh) · profile 数量 · python · node · 仓库自身完整性
    2. 生成 DSH 插件树补丁（插到 `~/.dsh/profiles/<profile>/cordis.patch.yml`）：
         · hooks-claude-code   —— 把 `.claude/hooks.json` 桥接给 DSH
         · aios-activation     —— 原生插件（`file:///…/runtime/aios-activation.ts`）
    3. 预演 / 写入（幂等：用标记块，重复运行为"更新"而非"追加"）
    4. 接入结果检查
    5. 打印"重启 + 验证"的下一步

边界（刻意保留的人工授权）
    · 改动的是**你自己的 DSH 配置** ⇒ 默认只预演，`--apply` 才落盘，且先备份
    · **不**替你打开任何注入能力 —— `.claude/aios-exposure.json` 保持默认全关
    · **不**重启 DSH 进程（重启由你执行；插件与 hook 配置都在启动时读取）
    · `--set-workspace-root` 才会改 `sandbox-policy`（默认不碰）

⛔ 只写 `cordis.patch.yml`（+ 备份）。不改仓库任何文件，不联网。
"""
import argparse
import datetime
import io
import os
import re
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "# >>> focusroute:begin"
END = "# <<< focusroute:end"
PLUGIN_HOOKS = "@deepseek-ai/dsh-hooks-claude-code"


def slashes(p):
    return p.replace("\\", "/")


def dsh_home(explicit=None):
    if explicit:
        p = os.path.abspath(explicit)
        return p if os.path.isdir(p) else None
    env = os.environ.get("DSH_HOME")
    if env and os.path.isdir(env):
        return os.path.abspath(env)
    cand = os.path.join(os.path.expanduser("~"), ".dsh")
    return cand if os.path.isdir(cand) else None


def list_profiles(home):
    base = os.path.join(home, "profiles")
    if not os.path.isdir(base):
        return []
    out = []
    for n in sorted(os.listdir(base)):
        p = os.path.join(base, n)
        if os.path.isdir(p) and n != "node_modules" and os.path.isfile(os.path.join(p, "cordis.patch.yml")):
            out.append((n, os.path.join(p, "cordis.patch.yml")))
    return out


def read_text(p):
    with io.open(p, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read()


def build_block(repo, workspace_root=None):
    r = slashes(repo)
    lines = [
        BEGIN + " (generated by tools/install.py · 请勿手改此块)",
        "# AI-OS 接入 —— hook 桥接 + 原生插件",
        "- insert:",
        "    - id: hooks-claude-code",
        "      name: '" + PLUGIN_HOOKS + "'",
        "      config:",
        "        configPath: " + r + "/.claude/hooks.json",
        "        projectDir: " + r,
        "- insert:",
        "    - id: aios-activation",
        "      name: 'file:///" + r + "/runtime/aios-activation.ts'",
    ]
    if workspace_root:
        # ⚠️ patch 语义 = 整体替换该 key（config 必须写全）
        lines += [
            "- id: sandbox-policy",
            "  config:",
            "    mode: !!js process.env.DSH_PERMISSION_MODE ?? 'workspace-write'",
            "    workspaceRoot: " + slashes(workspace_root),
        ]
    lines.append(END)
    return "\n".join(lines) + "\n"


def merge(existing, block):
    """幂等合并：已有标记块 ⇒ 替换；否则追加。返回 (新文本, 动作)"""
    if BEGIN in existing:
        pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
        if BEGIN in existing and END not in existing:
            return None, "block-unterminated"
        return pat.sub(block, existing, count=1), "replaced"
    # dsh 的 profile 模板是「注释 + 顶层空数组 `[]`」。把序列项直接追加在 `[]`
    # 之后会得到**非法 YAML**（一个文档只能有一个根节点）—— 首次接入必然踩到。
    # 追加前先摘掉这个空数组占位。
    if re.search(r"^\[\]\s*$", existing, re.M) and not re.search(r"^\s*-\s", existing, re.M):
        existing = re.sub(r"^\[\]\s*\n?", "", existing, count=1, flags=re.M)
    sep = "" if existing.endswith("\n") or not existing.strip() else "\n"
    return existing + sep + block, "appended"


def check_yaml(patch, home):
    """真解析一遍产物 YAML。

    仅做字符串包含检查会漏掉「块在、文件却语法非法」这种情况（例如 `[]` 之后
    追加序列项）。用 dsh 自带的 js-yaml（优先），拿不到就跳过 —— 不阻塞接入。
    """
    js = (
        "const fs=require('fs');"
        "const p=process.argv[1];"
        "let yaml=null;"
        "for(const c of process.argv.slice(2)){try{yaml=require(c);break}catch(_){}}"
        "if(!yaml){process.stdout.write('SKIP');process.exit(0)}"
        # DSH 的 patch 方言含自定义标量标签 `!!js`（cordis-plugin-include 的 entryListSchema）
        # ⇒ 用默认 schema 检查会误报 unknown tag。这里显式把该标签声明为普通标量
        #   （读数：带 --set-workspace-root 写入 sandbox-policy 后必踩）。
        "const jsTag=new yaml.Type('tag:yaml.org,2002:js',{kind:'scalar',resolve:()=>true});"
        "const schema=yaml.DEFAULT_SCHEMA.extend([jsTag]);"
        "try{yaml.load(fs.readFileSync(p,'utf8'),{schema});process.stdout.write('OK')}"
        "catch(e){process.stdout.write('BAD '+String(e.message).split('\\n')[0])}"
    )
    cands = [
        os.path.join(home, "profiles", "node_modules", "js-yaml"),
        os.path.join(os.path.expanduser("~"), ".dsh", "profiles", "node_modules", "js-yaml"),
        "js-yaml",
        "yaml",
    ]
    try:
        r = subprocess.run(["node", "-e", js, patch] + cands, capture_output=True,
                           text=True, encoding="utf-8", errors="replace", timeout=30)
        out = (r.stdout or "").strip()
    except Exception as exc:
        return True, "（跳过：%s）" % exc
    if out == "OK":
        return True, ""
    if out == "SKIP":
        return True, "（跳过：未找到 js-yaml）"
    detail = out[4:] if out.startswith("BAD ") else out
    return False, "（%s）" % detail[:160]


def run(cmd):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=30)
        return (r.stdout or r.stderr or "").strip().splitlines()[0] if (r.stdout or r.stderr) else ""
    except Exception:
        return ""


def env_checks(repo, home):
    rows = []

    def add(name, ok, detail, optional=False):
        rows.append((name, ok, detail, optional))

    add("仓库根", os.path.isfile(os.path.join(repo, "README.md")) and
        os.path.isdir(os.path.join(repo, "runtime")), slashes(repo))
    add("原生插件", os.path.isfile(os.path.join(repo, "runtime", "aios-activation.ts")),
        "runtime/aios-activation.ts")
    hj = os.path.join(repo, ".claude", "hooks.json")
    htxt = read_text(hj) if os.path.isfile(hj) else ""
    # 两种合法写法：CC 方言的 ${CLAUDE_PROJECT_DIR}，或本仓库绝对路径。
    # ⚠️ JSON 里 Windows 路径写作 `<repo>\\…`（双反斜杠）⇒ 必须先归一化再比对，
    #    否则会把「写对了但被 JSON 转义」误判成失败（实际踩到）。
    hnorm = htxt.replace("\\\\", "/").replace("\\", "/")
    add("hook 配置", bool(htxt) and ("${CLAUDE_PROJECT_DIR}" in htxt
                                     or slashes(repo) + "/tools/aios-hook.py" in hnorm),
        ".claude/hooks.json（含 ${CLAUDE_PROJECT_DIR} 或本仓库绝对路径）")
    add("工具入口", os.path.isfile(os.path.join(repo, "tools", "aios-hook.py")),
        "tools/aios-hook.py")
    add("机制探针", os.path.isfile(os.path.join(repo, "tools", "probes", "_field_emit.py")),
        "tools/probes/" if os.path.isdir(os.path.join(repo, "tools", "probes"))
        else "本仓库未包含 tools/probes/（非接入必需 · 不计入未通过）", optional=True)
    add("python", sys.version_info >= (3, 8), "%d.%d.%d" % sys.version_info[:3])
    node = run(["node", "--version"])
    add("node（DSH 运行依赖）", bool(node), node or "未找到 —— DSH 自身需要 node")
    add("DSH home", bool(home), home or "未找到 ~/.dsh ⇒ **DSH 尚未安装**（本接入器只把 FocusRoute 接进 DSH）")
    return rows


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    ap = argparse.ArgumentParser(description="FocusRoute 接入器（DSH）")
    ap.add_argument("--apply", action="store_true", help="真正写入（默认只预演）")
    ap.add_argument("--list", action="store_true", help="只显示环境与 profile")
    ap.add_argument("--profile", default=None, help="目标 profile 名（默认自动选择）")
    ap.add_argument("--dsh-home", default=None, help="DSH home（默认 ~/.dsh）")
    ap.add_argument("--set-workspace-root", default=None,
                    help="同时把 sandbox-policy.workspaceRoot 设为该路径（默认不碰）")
    ap.add_argument("--repo", default=None,
                    help="要接入的仓库根（默认 = 本脚本所在仓库）")
    args = ap.parse_args()

    global REPO
    if args.repo:
        REPO = os.path.abspath(args.repo)
    home = dsh_home(args.dsh_home)
    print("AI-OS 接入器")
    print("  仓库: %s" % slashes(REPO))
    print("  DSH : %s" % (home or "(未找到)"))
    print()

    print("── 环境检查 ──")
    bad = 0
    for name, ok, detail, optional in env_checks(REPO, home):
        print("  %s %-22s %s" % ("✅" if ok else ("⚠️ " if optional else "❌"), name, detail))
        if not ok and not optional:
            bad += 1
    if bad:
        print("\n⛔ 有 %d 项未通过 —— 先解决再接入（列出的是检查项，不是猜测）。" % bad)
        if not home:
            print("""
   关于 DSH home：
     FocusRoute 是**接进 DSH 的插件包**，本身不需要 DSH 才能被 clone/阅读，
     但「接入」这一步必须有已安装的 DSH。
     ⇒ 请先安装并能启动 DSH，再回到本目录重跑本命令。
     ⇒ 若你的 DSH home 不在 ~/.dsh，用 `--dsh-home <路径>` 指定。""")
        return 1

    profs = list_profiles(home)
    print("\n── 可用 profile ──")
    if not profs:
        print("  ❌ 未找到任何 profile（%s/profiles/*/cordis.patch.yml）" % slashes(home))
        return 1
    for n, p in profs:
        has = "（已接入）" if BEGIN in read_text(p) else ""
        print("  · %-12s %s %s" % (n, slashes(p), has))
    if args.list:
        return 0

    target = args.profile
    if target is None:
        names = [n for n, _ in profs]
        target = "web" if "web" in names else names[0]
        print("\n  （未指定 --profile ⇒ 默认选 %s；可用 --profile 指定其它）" % target)
    hit = [p for n, p in profs if n == target]
    if not hit:
        print("\n⛔ profile 不存在：%s（可用：%s）" % (target, ", ".join(n for n, _ in profs)))
        return 1
    patch = hit[0]

    old = read_text(patch)
    block = build_block(REPO, args.set_workspace_root)

    # 冲突检测：已有同名 entry 但不是我们的块
    conflicts = []
    for pid in ("hooks-claude-code", "aios-activation"):
        if re.search(r"^\s*-?\s*id:\s*" + re.escape(pid) + r"\s*$", old, re.M):
            if BEGIN not in old:
                conflicts.append(pid)
    if conflicts:
        print("\n⚠️  目标 profile 已有同名条目（且不是本安装器写入的）：%s" % ", ".join(conflicts))
        print("    ⇒ 直接插入会产生**重复 id**（loader 可能报错）。")
        print("    请选择：① 手工合并进现有条目后重跑  ② 换 profile  ③ 临时移走那几行再重跑")
        return 2

    new, action = merge(old, block)
    if new is None:
        print("\n⛔ 检测到 `%s` 但缺少 `%s` —— 标记块被破坏，请手工修复后重跑。" % (BEGIN, END))
        return 2

    print("\n── 将要写入的补丁（%s · 动作=%s）──" % (slashes(patch), action))
    print("  " + "\n  ".join(block.rstrip("\n").splitlines()))
    if not args.apply:
        print("\n预演结束 —— **未写入任何文件**。确认无误后加 --apply 落盘：")
        print("    python tools/install.py --apply --profile %s" % target)
        return 0

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = patch + ".bak-" + stamp
    n = 1
    while os.path.exists(backup):          # 同一秒内重复运行 ⇒ 不覆盖既有备份
        n += 1
        backup = patch + ".bak-" + stamp + "-%d" % n
    shutil.copy2(patch, backup)
    with io.open(patch, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new)
    print("\n✅ 已写入（备份：%s）" % slashes(backup))

    print("\n── 接入结果检查 ──")
    after = read_text(patch)
    ok_block = BEGIN in after and END in after
    ok_paths = slashes(REPO) + "/.claude/hooks.json" in after and \
        "file:///" + slashes(REPO) + "/runtime/aios-activation.ts" in after
    ok_yaml, yaml_note = check_yaml(patch, home)
    print("  %s 补丁块已就位" % ("✅" if ok_block else "❌"))
    print("  %s 路径指向本仓库" % ("✅" if ok_paths else "❌"))
    print("  %s YAML 可解析%s" % ("✅" if ok_yaml else "❌", yaml_note))
    if not (ok_block and ok_paths and ok_yaml):
        print("\n⛔ 接入结果未全部通过 —— 请按上面失败项处理后再重启 DSH。")
        return 3

    print("""
── 下一步（必须，两步）────────────────────────────────────────────────────
  ① 重启 DSH —— 插件加载 **和** hook 配置都在启动时读取一次，不重启不生效：
       Windows:  D:\\deepseek-harness\\dsh.cmd restart
       其它:     按你的 DSH 启动方式重启（等价于 stop + start）

  ② 重启后跑验证：
       python tools/verify.py

  ⚠️ 能力默认**全关**（`.claude/aios-exposure.json`）：接入 ≠ 注入。
     要启用某项能力，改那个文件里的对应开关（一行即生效，无需重启）。
──────────────────────────────────────────────────────────────────────────""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
